// Measures the client JS each editor route loads on top of the app shell from the Vite manifest and writes src/data/bundle-sizes.ts.
// Usage: pnpm build && node scripts/bundle-sizes.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { gzipSync } from "node:zlib";

const EDITORS = ["plate", "blocknote", "lexical", "tiptap"];
const clientDir = "dist/client";
const manifest = JSON.parse(
	readFileSync(join(clientDir, ".vite/manifest.json"), "utf8"),
);

function reachable(keys) {
	const seen = new Set();
	const stack = [...keys];
	while (stack.length) {
		const key = stack.pop();
		if (seen.has(key) || !manifest[key]) continue;
		seen.add(key);
		stack.push(...(manifest[key].imports ?? []));
	}
	return seen;
}

const routeKeys = (id) =>
	Object.keys(manifest).filter((key) => key.startsWith(`src/routes/${id}.tsx`));
const shared = reachable(
	Object.keys(manifest).filter((key) => manifest[key].isEntry),
);
const sizes = {};
for (const id of EDITORS) {
	const keys = routeKeys(id);
	if (keys.length === 0) continue;
	// Follow the route's lazy component chunk too.
	const roots = keys.flatMap((key) => [
		key,
		...(manifest[key].dynamicImports ?? []),
	]);
	let raw = 0;
	let gzip = 0;
	for (const key of reachable(roots)) {
		if (shared.has(key)) continue;
		const code = readFileSync(join(clientDir, manifest[key].file));
		raw += code.length;
		gzip += gzipSync(code).length;
	}
	sizes[id] = {
		rawKb: Math.round(raw / 1024),
		gzipKb: Math.round(gzip / 1024),
	};
}

const out = `import type { EditorId } from "@/editors/types";

/**
 * Client JS each editor route loads on top of the app shell (route chunks + every dependency,
 * including ones another editor also uses), gzip. Generated by \`pnpm bundle-sizes\`; do not edit by hand.
 */
export const BUNDLE_SIZES: Partial<Record<EditorId, { rawKb: number; gzipKb: number }>> = ${JSON.stringify(sizes, null, "\t")};
`;
writeFileSync("src/data/bundle-sizes.ts", out);
console.log(sizes);
